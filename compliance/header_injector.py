# compliance/header_injector.py
"""
HeaderInjector: single source of truth for platform headers and rate limits.

Responsibilities:
- Load `<workspace>/platform_profile.json` generated by `main.py init`.[cite:1]
- Expose merged headers dict for Python tools.
- Export a flat `key: value` headers file for Go tools (read via HARNESS_HEADERS_FILE).[cite:1]
- Provide an async rate-limit context manager enforcing `rate_limit_rps`.
"""

from __future__ import annotations

import asyncio
import json
import os
import time
from dataclasses import dataclass
from typing import Dict, Any


@dataclass
class PlatformProfile:
    platform: str
    program_handle: str
    researcher_username: str
    headers: Dict[str, str]
    rate_limit_rps: float
    max_concurrent_requests: int
    auth: Dict[str, Any]


class HeaderInjector:
    def __init__(self, profile: PlatformProfile):
        self._profile = profile
        self._headers = dict(profile.headers)
        # Ensure User-Agent exists
        if "User-Agent" not in self._headers:
            self._headers["User-Agent"] = (
                f"Mozilla/5.0 (BugBounty; {profile.platform}/{profile.researcher_username})"
            )
        # Simple per-process rate limiter
        self._rate_limit_rps = profile.rate_limit_rps or 10.0
        self._min_interval = 1.0 / self._rate_limit_rps
        self._last_call = 0.0
        self._lock = asyncio.Lock()

    # -------- Construction --------

    @classmethod
    def from_profile(cls, profile_path: str) -> "HeaderInjector":
        """
        Load platform_profile.json from the given path.[cite:1]
        """
        with open(profile_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        profile = PlatformProfile(
            platform=data.get("platform", ""),
            program_handle=data.get("program_handle", ""),
            researcher_username=data.get("researcher_username", ""),
            headers=data.get("headers", {}) or {},
            rate_limit_rps=float(data.get("rate_limit_rps", 10.0)),
            max_concurrent_requests=int(data.get("max_concurrent_requests", 5)),
            auth=data.get("auth", {}) or {},
        )
        return cls(profile)

    # -------- Headers API --------

    def get_headers(self) -> Dict[str, str]:
        """
        Return the merged headers dict for Python HTTP clients.
        """
        return dict(self._headers)

    def export_headers_file(self, output_path: str) -> None:
        """
        Write a flat `key: value` headers file for Go tools (e.g. jsleak) to read via HARNESS_HEADERS_FILE.[cite:1]
        """
        lines = [f"{k}: {v}" for k, v in self._headers.items()]
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))

    # -------- Rate limiting --------

    async def rate_limit(self):
        """
        Async context manager enforcing `rate_limit_rps` on calls.

        Usage:
            async with injector.rate_limit():
                await session.get(...)
        """
        # This is implemented as a helper returning an async context manager.

        class _RateLimitCtx:
            def __init__(self, outer: "HeaderInjector"):
                self.outer = outer

            async def __aenter__(self):
                async with self.outer._lock:
                    now = time.monotonic()
                    elapsed = now - self.outer._last_call
                    if elapsed < self.outer._min_interval:
                        await asyncio.sleep(self.outer._min_interval - elapsed)
                    self.outer._last_call = time.monotonic()

            async def __aexit__(self, exc_type, exc, tb):
                # nothing to clean up
                return False

        return _RateLimitCtx(self)
